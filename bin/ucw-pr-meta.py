#!/usr/bin/env python3
"""Generate deterministic PR metadata from the current branch state.

Used by `/ucw ship` at auto-mode level 4 to seed the
`mcp__github__create_pull_request` call without the agent having to
improvise a title/body that drifts between runs.

Output (JSON to stdout):
    {
        "title":         "<first line of HEAD commit, truncated 70 chars>",
        "body":          "<markdown PR body>",
        "head_branch":   "<current branch name>",
        "base_branch":   "<args.base or 'main'>",
        "commit_sha":    "<HEAD sha>",
        "diff_stat":     "<short numstat>",
        "commits_ahead": <int — commits in head not in base>
    }

Exit codes:
    0 = ok
    1 = git command failed (probably not a repo or no commits)
    2 = head already merged into base (no PR needed)
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path


def _git(args: list[str], *, cwd: Path) -> str:
    cp = subprocess.run(
        ["git", *args], cwd=cwd, capture_output=True, text=True, check=True,
    )
    return cp.stdout.strip()


def _safe_git(args: list[str], *, cwd: Path, default: str = "") -> str:
    try:
        return _git(args, cwd=cwd)
    except (subprocess.CalledProcessError, FileNotFoundError):
        return default


def _validate_base(base: str) -> None:
    """Reject a base ref that could be parsed as a git option.

    `base` is interpolated into refspecs below (`{base}...HEAD`) and passed to
    git as an argv element. A value like `--output=/path` would otherwise be
    read as a flag (e.g. `git diff`'s --output writes to an arbitrary file).
    Git refnames cannot legitimately begin with `-`, so this loses nothing real.
    """
    if not base or base.startswith("-"):
        raise ValueError(f"invalid base ref (must not start with '-'): {base!r}")


def _title_from_commit(subject: str) -> str:
    """Trim subject to 70 chars without lopping mid-word."""
    s = subject.strip()
    if len(s) <= 70:
        return s
    cut = s[:70]
    sp = cut.rfind(" ")
    return (cut[:sp] if sp > 50 else cut).rstrip()


def _body_template(*, subject: str, body_paragraphs: str, diff_stat: str,
                   commits_ahead: int, head: str, base: str) -> str:
    summary = body_paragraphs.strip()
    if not summary:
        summary = f"_{subject.strip()}_"

    return f"""## Summary

{summary}

## Changes ({commits_ahead} commit{'s' if commits_ahead != 1 else ''} ahead of `{base}`)

```
{diff_stat or '(no diff stat available)'}
```

## Test plan

- [ ] Run the project's test suite locally
- [ ] Manually verify the user-facing behavior on the branch
- [ ] CI green on `{head}` before merging

---
Auto-generated by UCW auto-mode level 4. Disable with `/ucw auto off` or
`UCW_AUTO_MODE=off`. To regenerate this body manually, run
`bin/ucw-pr-meta.py --base {base}`.
"""


def generate_meta(repo: Path, base: str) -> dict:
    _validate_base(base)
    head_sha = _git(["rev-parse", "HEAD"], cwd=repo)
    head_branch = _git(["rev-parse", "--abbrev-ref", "HEAD"], cwd=repo)
    if head_branch == "HEAD":
        head_branch = head_sha[:12]  # detached — at least something stable

    commit_msg = _git(["log", "-1", "--pretty=%B", head_sha], cwd=repo)
    lines = commit_msg.split("\n")
    subject = lines[0]
    body_paragraphs = "\n".join(lines[1:]).strip()

    # If base doesn't resolve, skip diff stats but don't fail — fresh repos
    # without a `main` branch shouldn't break the helper.
    # `--end-of-options` ensures the interpolated ref is never read as a flag,
    # belt-and-suspenders alongside _validate_base above.
    if _safe_git(["rev-parse", "--verify", "--end-of-options", base], cwd=repo):
        diff_stat = _safe_git(
            ["diff", "--stat", "--end-of-options", f"{base}...HEAD"], cwd=repo,
        ) or "(no diff vs base)"
        try:
            commits_ahead = int(_git(
                ["rev-list", "--count", "--end-of-options", f"{base}..HEAD"], cwd=repo,
            ))
        except (subprocess.CalledProcessError, ValueError):
            commits_ahead = 0
    else:
        diff_stat = f"(base branch '{base}' not found)"
        commits_ahead = 0

    return {
        "title": _title_from_commit(subject),
        "body": _body_template(
            subject=subject,
            body_paragraphs=body_paragraphs,
            diff_stat=diff_stat,
            commits_ahead=commits_ahead,
            head=head_branch,
            base=base,
        ),
        "head_branch": head_branch,
        "base_branch": base,
        "commit_sha": head_sha,
        "diff_stat": diff_stat,
        "commits_ahead": commits_ahead,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="ucw-pr-meta",
        description="Deterministic PR title/body generator for /ucw ship at "
                    "auto-mode level 4.",
    )
    parser.add_argument("--repo", default=".", help="repo path (default: cwd)")
    parser.add_argument("--base", default="main",
                        help="base branch to compare against (default: main)")
    args = parser.parse_args(argv)

    repo = Path(args.repo).resolve()
    try:
        meta = generate_meta(repo, args.base)
    except ValueError as exc:
        print(json.dumps({"error": "invalid base ref", "detail": str(exc)}),
              file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as exc:
        print(json.dumps({"error": "git command failed", "detail": exc.stderr.strip()}),
              file=sys.stderr)
        return 1

    if meta["commits_ahead"] == 0 and meta["head_branch"] != args.base:
        # Not necessarily an error — but ship caller should know there's
        # nothing to PR.
        print(json.dumps({**meta, "warning": "no commits ahead of base"}, indent=2))
        return 2

    print(json.dumps(meta, indent=2))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except BrokenPipeError:
        sys.exit(0)
