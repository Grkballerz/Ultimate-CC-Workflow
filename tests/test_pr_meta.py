"""Tests for bin/ucw-pr-meta.py — the PR title/body generator used by
/ucw ship at auto-mode level 4."""
from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
BIN = REPO_ROOT / "bin" / "ucw-pr-meta.py"


def _run(args: list[str], cwd: Path) -> tuple[int, str, str]:
    cp = subprocess.run(
        [sys.executable, str(BIN), *args],
        cwd=cwd, capture_output=True, text=True, timeout=10,
    )
    return cp.returncode, cp.stdout, cp.stderr


def _git(args: list[str], cwd: Path, *, env: dict | None = None) -> None:
    e = os.environ.copy()
    e.update({
        "GIT_AUTHOR_NAME": "Test", "GIT_AUTHOR_EMAIL": "t@e.com",
        "GIT_COMMITTER_NAME": "Test", "GIT_COMMITTER_EMAIL": "t@e.com",
    })
    if env:
        e.update(env)
    # Disable signing — sandboxed test envs don't have the signing key
    subprocess.run(
        ["git", "-c", "commit.gpgsign=false", "-c", "tag.gpgsign=false", *args],
        cwd=cwd, check=True, env=e, capture_output=True, text=True,
    )


@pytest.fixture
def repo(tmp_path):
    """Init a real git repo so the helper can run git commands against it."""
    _git(["init", "-b", "main"], cwd=tmp_path)
    (tmp_path / "README.md").write_text("# Test\n")
    _git(["add", "README.md"], cwd=tmp_path)
    _git(["commit", "-m", "initial"], cwd=tmp_path)
    return tmp_path


